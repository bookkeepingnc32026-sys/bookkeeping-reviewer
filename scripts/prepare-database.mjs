import { readdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

export async function initialSetupSQL() {
  const files = (
    await readdir(new URL("../supabase/migrations/", import.meta.url))
  )
    .filter((name) => /^\d+_.+\.sql$/.test(name))
    .sort();
  const sections = await Promise.all(
    files.map(async (name) => {
      const sql = await readFile(
        new URL(`../supabase/migrations/${name}`, import.meta.url),
        "utf8",
      );
      // Each migration already has a transaction. Combine their bodies into one
      // transaction so either the entire fresh installation succeeds or none does.
      const body = sql
        .replace(/^begin;\s*$/gim, "")
        .replace(/^commit;\s*$/gim, "")
        .replace(/^notify pgrst, 'reload schema';\s*$/gim, "");
      return `-- Source: ${name}\n${body.trim()}`;
    }),
  );
  return `-- BOOKKEEP INITIAL DATABASE SETUP\n-- Generated by npm run db:prepare. Run once in your project's Supabase SQL editor.\n-- For a fresh database only. Do not run after the individual migrations succeeded.\n-- Existing Auth accounts are preserved and receive learner profiles.\nbegin;\n${sections.join("\n\n")}\nnotify pgrst, 'reload schema';\ncommit;\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const target = new URL("../supabase/setup.sql", import.meta.url);
  await writeFile(target, await initialSetupSQL(), "utf8");
  console.log(
    `Ready: ${fileURLToPath(target)}\nCopy the entire file into Supabase SQL Editor and run once.`,
  );
}
